CREATE TABLE SALA (
    IDSALA NUMBER PRIMARY KEY,
    CODIGO VARCHAR2(255 CHAR),
    NOMBRE VARCHAR2(255 CHAR),
    PRECIO NUMBER,
    PORCENTAJELINEA NUMBER,
    PORCENTAJEBINGO NUMBER,
    PORCENTAJEBOTE NUMBER,
    PREMIOBOTE NUMBER,
    BOLAMAXBOTE NUMBER DEFAULT 44,
    TIMESTAMP TIMESTAMP
);

CREATE TABLE PARTIDA (
    IDPARTIDA NUMBER PRIMARY KEY,
    IDSALA NUMBER NOT NULL,
    FECHAINICIO TIMESTAMP,
    FECHAFIN TIMESTAMP,
    PREMIOLINEA NUMBER,
    PREMIOBINGO NUMBER,
    ESTADO VARCHAR2(50),
    SALIOBOTE NUMBER(1) DEFAULT 0,
    TIMESTAMP TIMESTAMP,
    CONSTRAINT FK_PARTIDA_SALA FOREIGN KEY (IDSALA) REFERENCES SALA(IDSALA)
);

CREATE TABLE USUARIO (
    IDUSUARIO NUMBER PRIMARY KEY,
    NOMBREUSUARIO VARCHAR2(255 CHAR),
    SALDO NUMBER(19,2),
    PASSWORD VARCHAR2(255 CHAR),
    SALT VARCHAR2(255 CHAR),
    FECHAULTIMOACCESO TIMESTAMP,
    ACTIVO NUMBER(1) DEFAULT 1,
    TIMESTAMP TIMESTAMP
);

CREATE TABLE CARTON (
    IDCARTON NUMBER PRIMARY KEY,
    NUMEROS VARCHAR2(4000 CHAR),
    PREMIADOLINEA NUMBER(1) DEFAULT 0,
    PREMIADOBINGO NUMBER(1) DEFAULT 0,
    IDPARTIDA NUMBER NOT NULL,
    IDUSUARIO NUMBER NOT NULL,
    ESTAENJUEGO NUMBER(1) DEFAULT 0,
    TIMESTAMP TIMESTAMP,
    CONSTRAINT FK_CARTON_PARTIDA FOREIGN KEY (IDPARTIDA) REFERENCES PARTIDA(IDPARTIDA),
    CONSTRAINT FK_CARTON_USUARIO FOREIGN KEY (IDUSUARIO) REFERENCES USUARIO(IDUSUARIO)
);

CREATE TABLE HISTORIAL (
    IDHISTORIAL NUMBER PRIMARY KEY,
    CANTIDADACTUAL NUMBER(19,2),
    CANTIDADMODIFICAR NUMBER(19,2),
    CANTIDADRESTANTE NUMBER(19,2),
    ACCION NUMBER,
    TIPOMOVIMIENTO VARCHAR2(255 CHAR),
    IDUSUARIO NUMBER NOT NULL,
    TIMESTAMP TIMESTAMP,
    CONSTRAINT FK_HISTORIAL_USUARIO FOREIGN KEY (IDUSUARIO) REFERENCES USUARIO(IDUSUARIO)
);

CREATE TABLE BOLAEXTRAIDA (
    IDBOLAEXTRAIDA NUMBER PRIMARY KEY,
    IDPARTIDA NUMBER NOT NULL,
    NUMEROBOLA NUMBER,
    ORDEN NUMBER,
    TIMESTAMP TIMESTAMP,
    CONSTRAINT FK_BOLAEXTRAIDA_PARTIDA FOREIGN KEY (IDPARTIDA) REFERENCES PARTIDA(IDPARTIDA)
);

